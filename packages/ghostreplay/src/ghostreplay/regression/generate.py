"""Generate runnable pytest modules and machine-readable reports."""

from __future__ import annotations

import json
from collections.abc import Iterable
from pathlib import Path
from xml.etree import ElementTree as ET

from ..storage.files import safe_join
from .cases import RegressionCase, RegressionReport

_TEMPLATE = '''"""Regression test generated by GhostReplay.

Case: {title}
Scenario: {scenario} | agent variant: {variant} | expected: {expect}
Faults: {faults}

The case data lives in {case_file} (plain JSON, validated on load, never executed).
Re-generate with the dashboard's "Export pytest" button or `Lab.export_case`.
"""

from pathlib import Path

from ghostreplay.regression import load_case, run_case

CASE_FILE = Path(__file__).with_name("{case_file}")


def test_{func}() -> None:
    report = run_case(load_case(CASE_FILE))
    print(report.explain())
    assert report.outcome_matches_expectation, report.explain()
'''


def pytest_source(case: RegressionCase, case_file: str) -> str:
    faults = (
        ", ".join(f"{f.kind}@{f.target.name}#{f.target.occurrence or '*'}" for f in case.faults)
        or "none"
    )
    return _TEMPLATE.format(
        title=case.title.replace('"""', "'''"),
        scenario=case.scenario,
        variant=case.variant,
        expect=case.expect.upper(),
        faults=faults,
        case_file=case_file,
        func=case.id.replace("-", "_"),
    )


def write_case(case: RegressionCase, directory: str | Path) -> tuple[Path, Path]:
    """Write ``<id>.case.json`` and ``test_<id>.py`` inside ``directory`` (no traversal)."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    case_name = f"{case.id}.case.json"
    case_path = safe_join(directory, case_name)
    test_path = safe_join(directory, f"test_{case.id.replace('-', '_')}.py")
    case_path.write_text(case.model_dump_json(indent=2), encoding="utf-8")
    test_path.write_text(pytest_source(case, case_name), encoding="utf-8")
    return case_path, test_path


def reports_to_json(reports: Iterable[RegressionReport]) -> str:
    items = [r.model_dump(mode="json") for r in reports]
    return json.dumps(
        {
            "total": len(items),
            "passed": sum(1 for r in items if r["outcome_matches_expectation"]),
            "reports": items,
        },
        indent=2,
    )


def reports_to_junit(reports: Iterable[RegressionReport], suite: str = "ghostreplay") -> str:
    reports = list(reports)
    failures = sum(1 for r in reports if not r.outcome_matches_expectation)
    root = ET.Element("testsuite", name=suite, tests=str(len(reports)), failures=str(failures))
    for r in reports:
        tc = ET.SubElement(
            root,
            "testcase",
            classname=f"{r.app}.{r.scenario}",
            name=f"{r.case_id}[{r.variant}]",
            time=f"{r.duration_ms / 1000:.3f}",
        )
        if not r.outcome_matches_expectation:
            failed = [i.id for i in r.invariants if i.status == "failed"]
            msg = f"expected {r.expect.upper()} but got {r.verdict}; failed: {', '.join(failed) or 'none'}"
            ET.SubElement(tc, "failure", message=msg).text = r.explain()
        ET.SubElement(tc, "system-out").text = r.explain()
    return ET.tostring(root, encoding="unicode")
